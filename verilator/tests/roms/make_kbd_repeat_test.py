#!/usr/bin/env python3
"""Build kbd_repeat_test.rom: programs CRTC and then writes various repeat commands to port 1Bh."""
import sys

CRTC = [0x7f, 0x50, 0x60, 0x3a, 0x1f, 0x06, 0x19, 0x1c, 0xa0, 0x07, 0x60, 0x0f, 0, 0, 0, 0]
code = bytearray()
def emit(*b): code.extend(b)

# Disable interrupts, stack at 0
emit(0xf3, 0x31, 0x00, 0x00)

# Init CRTC
for r in range(15, -1, -1):
    emit(0x3e, r, 0xd3, 0x18, 0x3e, CRTC[r], 0xd3, 0x19)

# Enter setting mode
emit(0x3e, 0x10, 0xd3, 0x1b)

# Set repeat start to 500ms (RM=0, T=0 -> 0x40)
emit(0x3e, 0x40, 0xd3, 0x1b)

# Set repeat start to 2000ms (RM=0, T=15 -> 0x4f)
emit(0x3e, 0x4f, 0xd3, 0x1b)

# Set repeat interval to 20ms (RM=1, T=0 -> 0x60)
emit(0x3e, 0x60, 0xd3, 0x1b)

# Set repeat interval to 80ms (RM=1, T=3 -> 0x63)
emit(0x3e, 0x63, 0xd3, 0x1b)

# Exit setting mode
emit(0x3e, 0x00, 0xd3, 0x1b)

# Loop
loop = len(code)
emit(0x18, (loop - (len(code) + 2)) & 0xff)

open(sys.argv[1], 'wb').write(bytes(code) + b'\xff' * (0x4000 - len(code)))
