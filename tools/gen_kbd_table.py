#!/usr/bin/env python3
"""Generate rtl/smc777_kbd_table.svh from the Common Source Code Project's SMC-777 key table.

    tools/gen_kbd_table.py ../common_source_code/src/vm/smc777/memory.h > rtl/smc777_kbd_table.svh

CSP's table is keyed by Windows virtual keys on a Japanese keyboard and is scanned in order (the first pressed key
wins). The SMC-777 keyboard is ASCII-layout, so the virtual keys are mapped to PS/2 set 2 codes by key position on a
US (and JP 106) keyboard. Table position = priority = index into the pressed-key bitmap.
"""
import re
import sys

# Windows VK -> list of PS/2 set 2 codes (0x1xx = E0 prefix)
VK2PS2 = {
    0x70: [0x05], 0x71: [0x06], 0x72: [0x04], 0x73: [0x0C], 0x74: [0x03],   # F1-F5
    0x7A: [0x78],                     # F11 -> H key (CSP)
    0x23: [0x169],                    # END -> CLR
    0x2E: [0x171], 0x2D: [0x170], 0x24: [0x16C],
    0x25: [0x16B], 0x26: [0x175], 0x28: [0x172], 0x27: [0x174],
    0x1B: [0x76],
    0x31: [0x16], 0x32: [0x1E], 0x33: [0x26], 0x34: [0x25], 0x35: [0x2E],
    0x36: [0x36], 0x37: [0x3D], 0x38: [0x3E], 0x39: [0x46], 0x30: [0x45],
    0x61: [0x69], 0x62: [0x72], 0x63: [0x7A], 0x64: [0x6B], 0x65: [0x73],
    0x66: [0x74], 0x67: [0x6C], 0x68: [0x75], 0x69: [0x7D], 0x60: [0x70],
    0x6A: [0x7C], 0x6B: [0x79], 0x6C: [0x15A], 0x6D: [0x7B], 0x6E: [0x71], 0x6F: [0x14A],
    0xBD: [0x4E],                     # '-'
    0xDE: [0x55],                     # '=' position (JP '^')
    0xDC: [0x6A, 0x09, 0x0B],         # RUB OUT / ル: JP yen key, F10, F6
    0x08: [0x66],
    0x51: [0x15], 0x57: [0x1D], 0x45: [0x24], 0x52: [0x2D], 0x54: [0x2C],
    0x59: [0x35], 0x55: [0x3C], 0x49: [0x43], 0x4F: [0x44], 0x50: [0x4D],
    0xC0: [0x54],                     # '[' position (JP '@')
    0xDB: [0x5B],                     # ']' position (JP '[')
    0x7B: [0x07],                     # F12 -> LF
    0x41: [0x1C], 0x53: [0x1B], 0x44: [0x23], 0x46: [0x2B], 0x47: [0x34],
    0x48: [0x33], 0x4A: [0x3B], 0x4B: [0x42], 0x4C: [0x4B],
    0xBB: [0x4C],                     # ';'
    0xBA: [0x52],                     # quote position (JP ':')
    0xDD: [0x0E],                     # '`' / '~': US backtick key
    0x0D: [0x5A],
    0x5A: [0x1A], 0x58: [0x22], 0x43: [0x21], 0x56: [0x2A], 0x42: [0x32],
    0x4E: [0x31], 0x4D: [0x3A],
    0xBC: [0x41], 0xBE: [0x49], 0xBF: [0x4A],
    0xE2: [0x5D, 0x51, 0x61],         # '\' '|': US backslash, JP ro, ISO 102nd
    0x09: [0x0D], 0x20: [0x29],
}

src = open(sys.argv[1], 'rb').read().decode('cp932', 'replace')
body = src[src.index('key_table_base[]'):]
body = body[:body.index('};')]
rows = re.findall(r'\{\s*(0x[0-9a-f]+),\s*(0x[0-9a-f]+),\s*(0x[0-9a-f]+),\s*(0x[0-9a-f]+),\s*(0x[0-9a-f]+),\s*(0x[0-9a-f]+),\s*(-?\d)\s*\}', body)
assert len(rows) <= 128

out = ['// Generated by tools/gen_kbd_table.py from CSP src/vm/smc777/memory.h key_table_base. Do not edit.',
       '// kbd_index: PS/2 {E0, code} -> table position (priority), 7\'h7f = no key.',
       '// kbd_codes: position -> {flag[1:0], code, shift, ctrl, kana, kana_shift}; flag 0: normal,',
       '//            1: no shift/ctrl/kana (numeric pad), 2: forced shift.',
       'function automatic [6:0] kbd_index(input [8:0] k);',
       '\tcase (k)']
seen = set()
for i, r in enumerate(rows):
    for p in VK2PS2[int(r[0], 16)]:
        assert p not in seen, hex(p)
        seen.add(p)
        out.append(f"\t9'h{p:03x}: kbd_index = 7'd{i};")
out += ["\tdefault: kbd_index = 7'h7f;", '\tendcase', 'endfunction', '',
        'function automatic [41:0] kbd_codes(input [6:0] i);', '\tcase (i)']
for i, r in enumerate(rows):
    flag = {'-1': 0, '0': 1, '1': 2}[r[6]]
    codes = ''.join(f'{int(x, 16):02x}' for x in r[1:6])
    out.append(f"\t7'd{i}: kbd_codes = {{2'd{flag}, 40'h{codes}}};")
out += ["\tdefault: kbd_codes = 42'd0;", '\tendcase', 'endfunction', '',
        f'localparam KBD_KEYS = {len(rows)};']
print('\n'.join(out))
